#!/bin/bash
# Give the container a working git identity: name, email, SSH auth and SSH commit
# signing, without dragging macOS-only paths in from the host config.
#
# The host's ~/.gitconfig is bind-mounted read-only at ~/.gitconfig-host and pulled in
# with an [include], so identity stays in sync. Overrides come after the include on
# purpose: git config is last-wins.
#
# Signing works in one of two modes, picked automatically:
#
#   agent mode (preferred)  1Password's SSH agent socket is forwarded from the host at
#                           $SSH_AUTH_SOCK. No key material enters the container: the
#                           agent protocol can only list public keys and sign blobs.
#                           Every use can require Touch ID approval on the host.
#
#   key-file mode (fallback) One private key is bind-mounted at ~/.ssh-key-host and
#                           copied into place. Used when socket forwarding isn't
#                           available (Docker Desktop's older gRPC-FUSE backend can't
#                           forward unix sockets). The key is readable in here, so a
#                           bypassed session could exfiltrate it.
#
# Either way gpg.ssh.program has to be overridden: the host points at 1Password's
# op-ssh-sign, a macOS binary that cannot execute in a Linux container.
set -euo pipefail

HOST_GITCONFIG="$HOME/.gitconfig-host"
HOST_KEY="$HOME/.ssh-key-host"
KEY="$HOME/.ssh/git_key"
ALLOWED_SIGNERS="$HOME/.config/git/allowed_signers"

# Rewritten from scratch every create, so re-running never stacks duplicate sections.
{
    echo "# Generated by /usr/local/bin/setup-git-identity.sh. Edits are lost on rebuild."
    echo "[include]"
    echo "	path = $HOST_GITCONFIG"
} >"$HOME/.gitconfig"

if [ ! -e "$HOST_GITCONFIG" ]; then
    echo "WARNING: $HOST_GITCONFIG is not mounted; container has no git identity" >&2
fi

install -m 700 -d "$HOME/.ssh"

# Common to both modes. ssh-keygen replaces op-ssh-sign as the signer.
git config --global gpg.format ssh
git config --global gpg.ssh.program ssh-keygen

# Turn a public key of any shape into the bare "type base64" pair that
# allowed_signers wants, dropping any trailing comment.
key_pair() { cut -d' ' -f1-2; }

write_allowed_signers() {
    # Only consulted when verifying. The host's copy lives at a macOS path, so build a
    # container-local one covering the key we sign with; otherwise `git log
    # --show-signature` reports an unknown principal instead of a good signature.
    install -m 700 -d "$(dirname "$ALLOWED_SIGNERS")"
    printf '%s %s\n' \
        "$(git config --get user.email || echo unknown)" \
        "$(printf '%s' "$1" | key_pair)" >"$ALLOWED_SIGNERS"
    git config --global gpg.ssh.allowedSignersFile "$ALLOWED_SIGNERS"
}

disable_signing() {
    git config --global commit.gpgsign false
    git config --global tag.gpgsign false
    echo "Git identity configured for commits, signing DISABLED: $1" >&2
}

# --- agent mode ------------------------------------------------------------------
if [ -n "${SSH_AUTH_SOCK:-}" ] && [ -S "${SSH_AUTH_SOCK}" ]; then
    # Listing needs 1Password unlocked on the host. Bounded, so a locked vault fails
    # the create hook fast instead of hanging on a prompt nobody will answer.
    if ! agent_keys=$(timeout 10 ssh-add -L 2>&1); then
        disable_signing "agent at $SSH_AUTH_SOCK unreachable or 1Password locked: $agent_keys"
        exit 0
    fi

    # Prefer the key the host already names, so the same key signs in both places. It
    # is stored as a literal public key rather than a path, which is exactly what makes
    # ssh-keygen ask the agent to sign (git passes -U for literals).
    signing_key=$(git config --get user.signingkey || true)
    case "$signing_key" in
        ssh-* | key::*) ;;
        *)
            signing_key=$(printf '%s\n' "$agent_keys" | head -1)
            echo "NOTE: host user.signingkey is not a literal public key; using the agent's first key" >&2
            ;;
    esac

    if [ -z "$signing_key" ]; then
        disable_signing "agent holds no keys"
        exit 0
    fi

    if ! printf '%s\n' "$agent_keys" | key_pair | grep -qxF "$(printf '%s' "$signing_key" | key_pair)"; then
        # Usually means agent.toml scopes the agent to a vault that lacks this key.
        disable_signing "the agent does not hold $(printf '%s' "$signing_key" | cut -c1-40)..."
        exit 0
    fi

    git config --global user.signingkey "$signing_key"
    write_allowed_signers "$signing_key"

    # No IdentityFile or IdentitiesOnly here: both would stop ssh offering agent keys.
    cat >"$HOME/.ssh/config" <<EOF
Host *
  StrictHostKeyChecking accept-new
EOF
    chmod 600 "$HOME/.ssh/config"

    echo "Git identity configured for $(git config --get user.name || echo '?') <$(git config --get user.email || echo '?')>."
    echo "Signing via forwarded SSH agent, $(printf '%s\n' "$agent_keys" | grep -c .) key(s) available. No key material in the container."
    exit 0
fi

# --- key-file mode ---------------------------------------------------------------
if [ ! -e "$HOST_KEY" ]; then
    disable_signing "no agent at \$SSH_AUTH_SOCK and no key at $HOST_KEY"
    exit 0
fi

# Copy rather than use the mount directly: ssh refuses key files whose ownership and
# mode it doesn't like, and a read-only bind mount carries the host's uid.
install -m 600 "$HOST_KEY" "$KEY"

# ssh-keygen derives the public half from the private key, which only works without a
# passphrase. A passphrase-protected key would prompt, and nothing here can answer.
if ! ssh-keygen -y -P "" -f "$KEY" >"$KEY.pub" 2>/dev/null; then
    rm -f "$KEY" "$KEY.pub"
    disable_signing "could not read $HOST_KEY (passphrase-protected?)"
    exit 0
fi
chmod 644 "$KEY.pub"

# A path, not a literal: without an agent, ssh-keygen has to read the private key.
git config --global user.signingkey "$KEY"
git config --global core.sshCommand "ssh -i $KEY -o IdentitiesOnly=yes"
write_allowed_signers "$(cat "$KEY.pub")"

cat >"$HOME/.ssh/config" <<EOF
Host *
  StrictHostKeyChecking accept-new
  IdentityFile $KEY
  IdentitiesOnly yes
EOF
chmod 600 "$HOME/.ssh/config"

echo "Git identity configured for $(git config --get user.name || echo '?') <$(git config --get user.email || echo '?')>."
echo "Signing via copied key file $KEY (readable in-container; prefer agent forwarding)."
